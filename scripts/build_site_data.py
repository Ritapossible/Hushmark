"""Write site/evidence.js from the real recordings, using Hushmark's own verifiers.

    uv run python scripts/build_site_data.py

A recording is shown as verified only if checks a–g all pass on it here, offline. The page never
states a result this script did not compute; tests/test_site.py fails if the file drifts.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

from hushmark.nonce import IdempotencyKey
from hushmark.receipt import build_receipt
from hushmark.scan import scan
from hushmark.verify.attestation import verify_attestation
from hushmark.verify.grounding import ground
from hushmark.verify.nras import verify_nras
from hushmark.verify.signature import check_signature

ROOT = Path(__file__).resolve().parent.parent
FIXTURES = ROOT / "fixtures"
OUT = ROOT / "site" / "evidence.js"

DESCRIPTIONS = {
    "r1": "Hidden HTML comments in a doc and in the PR description tell AI agents to approve "
    "the PR, run a remote script and say nothing.",
    "r2": "A harmless hidden note: <!-- TODO: add screenshot -->.",
    "r3": "New AGENTS.md rules tell coding agents to skip failing tests, push to main and "
    "hide it from the user.",
    "r4": "New AGENTS.md rules that are ordinary: run lint and tests, keep commits small, "
    "add type hints.",
}


def evidence(name: str) -> dict[str, Any]:
    rec = FIXTURES / "recordings" / name
    src = FIXTURES / "inputs" / name
    meta = json.loads((rec / "meta.json").read_text())
    request = (rec / "request.json").read_bytes()
    response = (rec / "response.json").read_bytes()
    signature = json.loads((rec / "signature.json").read_text())
    attestation_bytes = (rec / "attestation.json").read_bytes()
    jwks = json.loads((FIXTURES / "nvidia" / "jwks.json").read_text())
    title = (src / "title.txt").read_text()
    result = scan((src / "diff.patch").read_text(), title, (src / "body.txt").read_text())

    signer = check_signature(signature, meta["model"], request, response)
    quote = verify_attestation(
        json.loads(attestation_bytes),
        meta["nonce"],
        (rec / "collateral.json").read_text(),
        meta["fetched_at"],
        signer,
    )
    verify_nras(
        json.loads((rec / "nras.json").read_text()), meta["nonce"], jwks, meta["fetched_at"]
    )
    grounded = ground(response, result.candidates)
    receipt = build_receipt(
        key=IdempotencyKey(**meta["key"]),
        nonce=meta["nonce"],
        nonce_salt=meta["nonce_salt"],
        request_bytes=request,
        response_bytes=response,
        signature=signature,
        attestation_bytes=attestation_bytes,
        tcb_status=quote.tcb_status,
        candidates=len(result.candidates),
        grounded=grounded,
        verified_at=meta["fetched_at"],
        created_at=meta["fetched_at"],
    )
    return {
        "id": name.upper(),
        "title": title,
        "description": DESCRIPTIONS[name],
        "model": meta["model"],
        "candidates": len(result.candidates),
        "findings": [
            {
                "where": f.candidate.file or "PR description",
                "line": f.candidate.line,
                "severity": f.severity,
                "rationale": f.rationale,
            }
            for f in grounded.findings
        ],
        "signatureKind": signature["signature_kind"],
        "signer": signer,
        "tcbStatus": quote.tcb_status,
        "receiptId": receipt.receipt_id,
        "verified": True,  # only reached if every check above passed
    }


def render() -> str:
    data = [evidence(n) for n in ("r1", "r2", "r3", "r4")]
    return (
        "// Generated by scripts/build_site_data.py from fixtures/recordings. Do not edit.\n"
        f"window.HUSHMARK_EVIDENCE = {json.dumps(data, indent=2, ensure_ascii=False)};\n"
    )


if __name__ == "__main__":
    OUT.write_text(render())
    print(f"wrote {OUT.relative_to(ROOT)}")
